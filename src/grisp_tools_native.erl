-module(grisp_tools_native).

-export([collect/1, patch/1, prepare/1, hash_index/1, inspect/2, strip_release/2]).

-define(FRAGMENT, "grisp-native.mk").
-define(MARKER, <<"# GRiSP generated static NIFs">>).

%% Archive providers need not depend on grisp or provide a source overlay.
collect(#{apps := Apps} = State) ->
    Nifs = lists:sort(lists:flatmap(fun({_App, Info}) ->
        maps:get(native_nifs, Info, [])
    end, maps:to_list(Apps))),
    mapz:deep_put([build, native_nifs], Nifs, State).

hash_index(State) ->
    Nifs = nifs(State),
    Integration = case Nifs of
        [] -> [];
        _ ->
            Hash = crypto:hash(sha256, [header(), fragment(Nifs)]),
            [{<<"native/integration">>, iolist_to_binary([
                io_lib:format("~2.16.0b", [Byte]) || <<Byte>> <= Hash])}]
    end,
    Integration ++
    lists:flatmap(fun(N) ->
        Key = iolist_to_binary(["native/", atom_to_list(maps:get(app, N)), "/", maps:get(name, N)]),
        [{Key, maps:get(hash, N)}] ++ case maps:find(inputs_hash, N) of
            {ok, InputsHash} -> [{<<Key/binary, "/inputs">>, InputsHash}];
            error -> []
        end
    end, Nifs).

%% Keep generated edits outside the context of the existing C overlay patches.
patch(#{paths := #{build := Root}} = State) ->
    Makefile = filename:join(Root, "erts/emulator/Makefile.in"),
    {ok, Original} = file:read_file(Makefile),
    case nifs(State) =/= [] orelse binary:match(Original, ?MARKER) =/= nomatch of
        false -> State;
        true ->
            check_otp(State, nifs(State)),
            write_changed(Makefile, integrate(Original)),
            State
    end.

prepare(#{paths := #{build := Root}} = State0) ->
    State1 = patch(State0),
    {ok, Makefile} = file:read_file(filename:join(Root, "erts/emulator/Makefile.in")),
    case nifs(State1) =/= [] orelse binary:match(Makefile, ?MARKER) =/= nomatch of
        false -> State1;
        true ->
            State2 = lists:foldl(fun(N, S) -> copy_archive(Root, N, S) end,
                                State1, nifs(State1)),
            write_changed(filename:join(Root, ?FRAGMENT), fragment(nifs(State2))),
            State2
    end.

nifs(State) -> mapz:deep_get([build, native_nifs], State, []).

check_otp(_State, []) -> ok;
check_otp(#{otp_version := {[Major | _], _, _, _}}, _) when Major >= 28 -> ok;
check_otp(_, _) -> error(native_nifs_require_otp_28).

archive(N) ->
    filename:join(["grisp-native", atom_to_list(maps:get(app, N)),
                   binary_to_list(maps:get(name, N)) ++ ".a"]).

copy_archive(Root, N, State0) ->
    File = #{app => maps:get(app, N), name => archive(N)},
    State1 = grisp_tools_util:event(State0, [File]),
    {ok, Data} = file:read_file(maps:get(source, N)),
    write_changed(filename:join(Root, archive(N)), Data),
    State1.

fragment(Nifs) ->
    Archives = [["$(ERL_TOP)/", archive(N)] || N <- Nifs],
    Entries = [["$(ERL_TOP)/", archive(N), ":",
                lists:join(":", maps:get(symbols, N))] || N <- Nifs],
    Symbols = [["$(ERL_TOP)/", archive(N), ":", Symbol]
               || N <- Nifs, Symbol <- maps:get(symbols, N)],
    ["# Generated by grisp_tools; do not edit.\n",
     "GRISP_NATIVE_ARCHIVES := ", lists:join(" ", Archives), "\n",
     case Nifs of
         [] -> [];
         _ -> ["ifeq ($(STATIC_NIFS),no)\n",
               "$(error GRiSP native NIFs require --enable-static-nifs)\nendif\n",
               "GRISP_NATIVE_NIFS := ", lists:join(" ", Entries), "\n",
               "GRISP_NATIVE_NIF_SYMBOLS := ", lists:join(" ", Symbols), "\n",
               "STATIC_NIFS += $(GRISP_NATIVE_NIFS)\n",
               %% OTP links each archive once, but its table parser accepts only
               %% one explicit entry per argument. Override its later assignment.
               "override STATIC_NIF_SYMBOLS = $(filter-out $(GRISP_NATIVE_NIFS),$(STATIC_NIFS)) ",
               "$(GRISP_NATIVE_NIF_SYMBOLS)\n"]
     end].

header() ->
    iolist_to_binary([
        ?MARKER, "\nifeq ($(findstring rtems,$(TARGET)),rtems)\n",
        "-include $(ERL_TOP)/", ?FRAGMENT, "\nendif\n",
        "GRISP_STATIC_NIF_LINK_LIBS = $(foreach lib,$(STATIC_NIF_LIBS),",
        "$(if $(filter $(lib),$(GRISP_NATIVE_ARCHIVES)),",
        "-Wl$(comma)--whole-archive $(lib) -Wl$(comma)--no-whole-archive,$(lib)))\n\n"
    ]).

integrate(Original) ->
    Header = header(),
    Anchor = <<"STATIC_DRIVERS=@STATIC_DRIVERS@">>,
    WithInclude = case binary:match(Original, <<Header/binary, Anchor/binary>>) of
        nomatch ->
            case {binary:match(Original, ?MARKER), binary:match(Original, Anchor)} of
                {nomatch, {_, _}} -> binary:replace(Original, Anchor, <<Header/binary, Anchor/binary>>);
                _ -> error(native_nifs_unsupported_makefile)
            end;
        _ -> Original
    end,
    Rule = <<"$(TTF_DIR)/driver_tab.c: Makefile.in utils/make_driver_tab">>,
    Dependency = <<" $(wildcard $(ERL_TOP)/grisp-native.mk)">>,
    WithDependency = case binary:match(WithInclude, Dependency) of
        nomatch ->
            case binary:match(WithInclude, Rule) of
                nomatch -> error(native_nifs_unsupported_driver_rule);
                _ -> binary:replace(WithInclude, Rule, <<Rule/binary, Dependency/binary>>)
            end;
        _ -> WithInclude
    end,
    Lines = [case Line of
        <<"\t", _/binary>> -> binary:replace(Line, <<"$(STATIC_NIF_LIBS)">>,
                                       <<"$(GRISP_STATIC_NIF_LINK_LIBS)">>, [global]);
        _ -> Line
    end || Line <- binary:split(WithDependency, <<"\n">>, [global])],
    iolist_to_binary(lists:join("\n", Lines)).

write_changed(Path, Contents) ->
    Data = iolist_to_binary(Contents),
    case file:read_file(Path) of
        {ok, Data} -> ok;
        _ ->
            ok = filelib:ensure_dir(Path),
            ok = file:write_file(Path, Data)
    end.

%% Archive inspection is independent of Cargo and the calling package manager.
inspect(Path, Nm) ->
    case filename:extension(Path) of
        Extension when Extension =:= <<".a">>; Extension =:= ".a" ->
            Symbols = init_symbols(run(Nm, ["-g", "--defined-only", unicode:characters_to_list(Path)])),
            case Symbols of
                [] -> undefined;
                _ ->
                    {ok, Data} = file:read_file(Path),
                    #{source => Path, symbols => Symbols, hash => hex(crypto:hash(sha256, Data))}
            end;
        _ -> undefined
    end.

%% Frontends identify their own host outputs; neither a layout nor an extension
%% is assumed here. Only assembled release files are removed.
strip_release(Root, Nifs) ->
    lists:foreach(fun(Nif) ->
        lists:foreach(fun(#{app := App, path := Path}) ->
            strip_artifact(Root, App, unicode:characters_to_list(Path))
        end, maps:get(host_artifacts, Nif, []))
    end, Nifs),
    ok.

strip_artifact(Root, App, Relative) ->
    Parts = filename:split(Relative),
    case filename:pathtype(Relative) =:= relative andalso
         length(Parts) >= 3 andalso hd(Parts) =:= "priv" andalso
         not lists:any(fun(P) -> P =:= ".." orelse P =:= "." end, Parts) of
        true -> ok;
        false -> error({native_release_invalid_path, Relative})
    end,
    Lib = filename:join(Root, "lib"),
    check_release_link(Root),
    check_release_link(Lib),
    AppDirs = filelib:wildcard(filename:join(Lib, atom_to_list(App) ++ "-*")),
    lists:foreach(fun(Dir) ->
        check_release_link(Dir),
        Path = lists:foldl(fun(Part, Parent) ->
            Child = filename:join(Parent, Part),
            check_release_link(Child),
            Child
        end, Dir, Parts),
        Result = case filelib:is_dir(Path) of
            true -> file:del_dir_r(Path);
            false -> file:delete(Path)
        end,
        case Result of
            ok -> ok;
            {error, enoent} -> ok;
            Error -> error({native_release_remove_failed, Path, Error})
        end
    end, AppDirs).

check_release_link(Path) ->
    case file:read_link(Path) of
        {ok, _} -> error({native_release_symlink, Path});
        _ -> ok
    end.

init_symbols(Output) ->
    lists:usort(
        lists:filtermap(
            fun(Line) ->
                Words = binary:split(Line, <<" ">>, [global, trim_all]),
                case Words of
                    [] ->
                        false;
                    _ ->
                        Symbol = lists:last(Words),
                        Suffix = <<"_nif_init">>,
                        Size = byte_size(Symbol) - byte_size(Suffix),
                        case Size > 0 of
                            false ->
                                false;
                            true ->
                                case Symbol of
                                    <<Prefix:Size/binary, Suffix/binary>> ->
                                        case
                                            re:run(Prefix, <<"^[A-Za-z_][A-Za-z0-9_]*$">>, [
                                                {capture, none}
                                            ])
                                        of
                                            match -> {true, Prefix};
                                            nomatch -> false
                                        end;
                                    _ ->
                                        false
                                end
                        end
                end
            end,
            binary:split(Output, <<"\n">>, [global])
        )
    ).

hex(Data) -> iolist_to_binary([io_lib:format("~2.16.0b", [B]) || <<B>> <= Data]).

run(Executable, Args) ->
    Port = open_port(
        {spawn_executable, Executable},
        [{args, Args}, binary, use_stdio, stderr_to_stdout, exit_status]
    ),
    receive_output(Port, []).
receive_output(Port, Acc) ->
    receive
        {Port, {data, Data}} -> receive_output(Port, [Data | Acc]);
        {Port, {exit_status, 0}} -> iolist_to_binary(lists:reverse(Acc));
        {Port, {exit_status, Code}} -> error({native_nm_failed, Code, Acc})
    end.
